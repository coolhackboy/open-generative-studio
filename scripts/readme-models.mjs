#!/usr/bin/env node
/**
 * Regenerates the supported-models table in README.md from src/data/catalog.json.
 *
 * Rewrites everything between
 *   <!-- models:start --> ... <!-- models:end -->
 * and the inline model count between
 *   <!-- models-count -->79<!-- /models-count -->
 *
 * Prices use src/lib/pricing.ts (Node 22.18+/23.6+ strips TypeScript types natively).
 * Usage: node scripts/readme-models.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const README = path.join(ROOT, 'README.md');
const catalog = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/data/catalog.json'), 'utf8'));

let pricing = null;
try {
  pricing = await import(pathToFileURL(path.join(ROOT, 'src/lib/pricing.ts')).href);
} catch (e) {
  console.warn(`! pricing.ts not importable (${e.message.split('\n')[0]}); prices fall back to the cheapest tier.`);
}

const UNIT = [
  [/second/i, '/s'],
  [/megapixel/i, '/MP'],
  [/image/i, '/image'],
  [/video/i, '/video'],
  [/generation|run/i, '/run'],
  [/token/i, '/1M tokens'],
];
const suffix = (unit) => UNIT.find(([re]) => re.test(unit))?.[1] ?? '';
const usd = (n) => (pricing?.formatUSD ? pricing.formatUSD(n) : `$${n < 0.1 ? n.toFixed(4).replace(/0+$/, '') : n.toFixed(2)}`);

function fromPrice(model) {
  let best = null;
  for (const v of model.variants) {
    const t = pricing?.startingPrice
      ? pricing.startingPrice(v)
      : (v.pricing.filter((p) => !/token/i.test(p.unit)).sort((a, b) => a.priceUSD - b.priceUSD)[0] ?? null);
    if (t && (!best || t.priceUSD < best.priceUSD)) best = t;
  }
  if (best) return `from ${usd(best.priceUSD)}${suffix(best.unit)}`;
  return model.variants.some((v) => v.pricing.length) ? 'billed by usage' : '—';
}

const esc = (s) => String(s).replace(/\|/g, '\\|');

function table(category) {
  const rows = catalog.models
    .filter((m) => m.category === category && m.variants.length > 0)
    .sort((a, b) => a.order - b.order)
    .map((m) => {
      const name = `[${esc(m.name)}](${m.pageUrl}?utm_source=github&utm_medium=readme&utm_campaign=open-generative-studio)`;
      const variants = m.variants.length > 1 ? m.variants.map((v) => esc(v.label)).join(', ') : '—';
      return `| ${name} | ${esc(m.provider)} | ${variants} | ${fromPrice(m)} |`;
    });
  return [
    `| Model | Provider | Variants | Price |`,
    `| --- | --- | --- | --- |`,
    ...rows,
  ].join('\n');
}

const models = catalog.models.filter((m) => m.variants.length > 0);
const videos = models.filter((m) => m.category === 'video').length;
const images = models.filter((m) => m.category === 'image').length;
const date = (catalog.generatedAt || '').slice(0, 10);

const block = `<!-- models:start -->
<!-- Generated by scripts/readme-models.mjs — do not edit by hand. -->

**${models.length} models** — ${videos} video, ${images} image${date ? ` · catalog snapshot ${date}` : ''}. Prices are the cheapest
public tier on PoYo at snapshot time; the app shows a live estimate for your exact settings and PoYo bills the final amount.

<details open>
<summary><b>Video models (${videos})</b></summary>

${table('video')}

</details>

<details>
<summary><b>Image models (${images})</b></summary>

${table('image')}

</details>
<!-- models:end -->`;

let readme = fs.readFileSync(README, 'utf8');
if (!/<!-- models:start -->[\s\S]*<!-- models:end -->/.test(readme)) {
  console.error('README.md has no <!-- models:start --> ... <!-- models:end --> block.');
  process.exit(1);
}
readme = readme.replace(/<!-- models:start -->[\s\S]*<!-- models:end -->/, block);
readme = readme.replace(/<!-- models-count -->\d+<!-- \/models-count -->/g, `<!-- models-count -->${models.length}<!-- /models-count -->`);
fs.writeFileSync(README, readme);
console.log(`README.md: wrote ${models.length} models (${videos} video, ${images} image).`);
